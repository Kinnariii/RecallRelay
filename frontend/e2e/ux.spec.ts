import { expect, test, type Page } from '@playwright/test'
import { auditScreen, captureScreen, sizeScreen } from './uxHelpers'

const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })
const heading = (page: Page, name: string) => page.getByRole('heading', { name })

async function approve(page: Page) {
  await button(page, 'Approve refunds · $24.00').click()
  const dialog = page.getByRole('dialog', { name: 'Approve sandbox refunds?' })
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Approve and refund $24.00' }).click()
}

for (const width of [1440, 1024, 390]) {
  test(`guided workflow and accessibility at ${width}px`, async ({ page, context }) => {
    test.setTimeout(90_000)
    await sizeScreen(page, width)
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    const screen = async (name: string, full = true) => {
      await captureScreen(page, name, full)
      await auditScreen(page, name)
    }

    await page.goto('/home')
    await heading(page, 'Refund the right customers. The right amount.').waitFor()
    await screen('home')
    await page.getByRole('link', { name: 'Start guided demo' }).click()
    await page.getByText('No demo orders yet').waitFor()
    await screen('setup-empty')
    const continueButton = button(page, 'Continue to upload notice')
    await continueButton.focus()
    await expect(page.getByRole('tooltip')).toBeVisible()
    await button(page, 'Find seed button').click()
    await expect(button(page, 'Seed demo orders')).toBeFocused()
    await button(page, 'Seed demo orders').click()

    const card = (name: string) => page.locator('.order-card').filter({ has: heading(page, name) })
    const capture = async (name: string) => {
      await card(name).getByRole('button', { name: 'Approve in PayPal sandbox' }).click()
      await expect(card(name).getByText('Captured', { exact: true })).toBeVisible()
    }
    await card('Asha Patel').waitFor()
    await screen('setup')
    await capture('Rohan Mehta')
    await expect(continueButton).toBeDisabled()
    await capture('Asha Patel')
    await capture('Meera Shah')
    await page.getByRole('link', { name: 'Continue to upload notice' }).click()
    await heading(page, 'Upload the supplier recall notice').waitFor()
    await screen('notice')
    const editor = page.getByRole('textbox', { name: 'Notice text' })
    const longNotice = 'x'.repeat(20_001)
    await editor.fill(longNotice)
    await expect(editor).toHaveValue(longNotice)
    await expect(button(page, 'Extract with AI')).toBeDisabled()
    await button(page, 'Clear').click()

    await page.getByRole('combobox', { name: 'Use a sample notice' }).selectOption('3')
    await button(page, 'Extract with AI').click()
    await page.getByText('Reading the notice and checking quotes…').waitFor()
    await captureScreen(page, 'extracting')
    await auditScreen(page, 'extracting')
    await page.getByText('This quote was not found in the notice. Please check it.').waitFor()
    await expect(button(page, 'Continue to review')).toBeDisabled()
    await screen('warnings')
    await button(page, 'Edit notice text').click()
    await page.getByRole('textbox', { name: 'Notice text' }).fill('A note with no recall information.')
    await button(page, 'Extract with AI').click()
    await heading(page, 'We couldn’t read this notice').waitFor()
    await screen('extraction-error')
    await button(page, 'Use sample notice 1').click()
    await expect(button(page, 'Extract with AI')).toBeFocused()
    await button(page, 'Extract with AI').click()
    await expect(page.getByRole('textbox', { name: 'Product SKU' })).toHaveValue('PB-340')
    const quote = page.locator('mark.quote-verified').filter({ hasText: 'B-200 through B-250' })
    await expect(quote).toBeVisible()
    await button(page, 'Quote 2, verified').focus()
    await expect(quote).toHaveClass(/quote-active/)
    await expect(button(page, 'Verified in notice · 2')).toHaveClass(/evidence-chip--active/)
    await heading(page, 'Check the product and lots').focus()
    await screen('evidence')
    await button(page, 'Continue to review').click()
    await expect(page.getByText('1 order to refund, 1 needs your review, 1 is not affected.')).toBeVisible()
    await expect(page.getByText('$24.00 of $68.00', { exact: true })).toBeVisible()
    await screen('review')
    const orderList = page.getByRole('region', { name: 'Refund plan and orders' })
    const orderBounds = await orderList.boundingBox()
    const approveBounds = await page.locator('.sticky-actions').boundingBox()
    expect(orderBounds!.y + orderBounds!.height).toBeLessThanOrEqual(approveBounds!.y + 1)
    await orderList.evaluate(element => { element.scrollTop = element.scrollHeight })
    await expect(heading(page, 'Rohan Mehta')).toBeInViewport()
    await expect(button(page, 'Approve refunds · $24.00')).toBeInViewport()
    await captureScreen(page, 'review-outcomes')
    await page.goto(page.url().replace('/review/', '/result/'))
    await heading(page, 'No refunds issued yet').waitFor()
    await screen('result-empty')
    await page.goBack()

    const approval = button(page, 'Approve refunds · $24.00')
    await approval.click()
    const dialog = page.getByRole('dialog', { name: 'Approve sandbox refunds?' })
    await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Close dialog' })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeFocused()
    await screen('approval', false)
    await page.keyboard.press('Escape')
    await expect(approval).toBeFocused()
    await approve(page)

    await heading(page, '$24.00 refunded').waitFor()
    await screen('result')
    await button(page, 'Copy refund ID').click()
    await expect(page.getByText('Copied refund ID.')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByText('Copied refund ID.')).toHaveCount(0)
    await button(page, 'Approve again').click()
    await expect(page.getByText('Already refunded. No duplicate created.')).toBeVisible()
    await captureScreen(page, 'repeat-approval', false)
    await auditScreen(page, 'repeat-approval')
    await button(page, 'View recall activity').click()
    await page.getByRole('dialog', { name: 'Recall activity' }).waitFor()
    await screen('activity', false)
    await page.keyboard.press('Escape')

    await page.goto('/?mockfail=1')
    await button(page, 'Use sample notice 1').click()
    await button(page, 'Extract with AI').click()
    await button(page, 'Continue to review').click()
    await approve(page)
    await heading(page, 'Refund needs attention').waitFor()
    await screen('failed')
    await button(page, 'Retry refund').click()
    await heading(page, '$24.00 refunded').waitFor()
    await page.goto('/missing')
    await heading(page, 'Page not found').waitFor()
    await screen('not-found')
  })
}

test('remembers the guide choice and honors a clean recording URL', async ({ page }) => {
  await page.goto('/setup')
  const toggle = button(page, 'Demo guide')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await toggle.click()
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await toggle.click()
  await page.goto('/home?demo=0')
  await page.getByRole('link', { name: 'Start guided demo' }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('complementary', { name: 'Demo guide' })).toHaveCount(0)
})
